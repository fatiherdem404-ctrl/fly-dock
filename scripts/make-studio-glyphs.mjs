// Reads the Lucide glyphs the icon studio uses (named in src/studio/keys.ts) out of node_modules/lucide-static and writes
// them, trimmed to their drawing elements, to src/studio/glyphs.generated.ts. Run after changing the key list.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
const keys = readFileSync('src/studio/keys.ts', 'utf8')
const names = [...new Set([...keys.matchAll(/\['[a-z0-9._-]+',\s*'[^']*',\s*'([a-z0-9-]+)'\]/g)].map((m) => m[1]))]
const out = {}
const missing = []
for (const n of names) {
  const f = `node_modules/lucide-static/icons/${n}.svg`
  if (!existsSync(f)) { missing.push(n); continue }
  const svg = readFileSync(f, 'utf8')
  out[n] = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s+/g, ' ').trim()
}
writeFileSync('src/studio/glyphs.generated.ts', `// Generated by scripts/make-studio-glyphs.mjs from Lucide (ISC licence, https://lucide.dev). Do not edit.\nexport const GLYPHS: Record<string, string> = ${JSON.stringify(out, null, 1)}\n`)
console.log(`${Object.keys(out).length} glyphs`, missing.length ? 'MISSING: ' + missing.join(', ') : '')
