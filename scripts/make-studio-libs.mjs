// Turns the extra icon libraries used by the icon studio's picker into one lazy-loaded file each, with every glyph
// already drawn in a 24 x 24 box (so the picker and the card renderer treat them like Lucide):
//   Tabler (MIT)               node_modules/@tabler/icons/icons/outline      -> stroke icons
//   Font Awesome Free (CC BY 4.0, icons)  .../svgs/solid, .../svgs/brands    -> filled icons
// Run after installing or updating the packages:  node scripts/make-studio-libs.mjs
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'

mkdirSync('src/studio/libs', { recursive: true })

function inner(svg) {
  return svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/<!--[\s\S]*?-->/g, '').replace(/\s+/g, ' ').trim()
}

function build(dir, out, header, filled) {
  const lib = {}
  for (const f of readdirSync(dir)) {
    if (!f.endsWith('.svg')) continue
    const svg = readFileSync(`${dir}/${f}`, 'utf8')
    let art = inner(svg)
    // the empty "bounding box" path every Tabler icon starts with draws nothing
    art = art.replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none" ?\/>/, '')
    if (filled) {
      const vb = /viewBox="([\d.\s-]+)"/.exec(svg)?.[1].split(/\s+/).map(Number) ?? [0, 0, 512, 512]
      const k = 24 / Math.max(vb[2], vb[3])
      const ox = (24 - vb[2] * k) / 2, oy = (24 - vb[3] * k) / 2
      art = `<g transform="translate(${+ox.toFixed(3)} ${+oy.toFixed(3)}) scale(${+k.toFixed(5)})">${art}</g>`
    }
    lib[f.slice(0, -4)] = art
  }
  writeFileSync(out, `// Generated by scripts/make-studio-libs.mjs. ${header}. Do not edit.\nexport const GLYPHS: Record<string, string> = ${JSON.stringify(lib)}\n`)
  console.log(out, Object.keys(lib).length)
}

build('node_modules/@tabler/icons/icons/outline', 'src/studio/libs/tabler.generated.ts', 'Tabler Icons, MIT licence, https://tabler.io/icons', false)
build('node_modules/@fortawesome/fontawesome-free/svgs/solid', 'src/studio/libs/fa-solid.generated.ts', 'Font Awesome Free (icons CC BY 4.0), https://fontawesome.com/license/free', true)
build('node_modules/@fortawesome/fontawesome-free/svgs/brands', 'src/studio/libs/fa-brands.generated.ts', 'Font Awesome Free (icons CC BY 4.0), https://fontawesome.com/license/free', true)
